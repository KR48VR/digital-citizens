def norm(p):
    s = float(sum(p))
    return [x / s for x in p]

def scale(base, k=0.0, mid=1.0, first=None, last=None):
    p = [b * math.exp(k * (i + 1 - 5.5)) for i, b in enumerate(base)]
    p[4] *= mid
    p = norm(p)
    for idx, t in ((0, first), (-1, last)):
        if t is not None:
            rest = sum(p) - p[idx]
            f = (1 - t) / rest
            p = [x * f for x in p]
            p[idx] = t
    return norm(p)

