"""Do people's changes of answer cancel out across a group? Twin-2K-500, same people asked twice.

For each retest item (same question in waves 1-3 and in wave 4, about two weeks apart), among people who
answered both times:
- individual match: share of people giving the same answer both times;
- group shift: points off per answer option between the two times' answer shares (the scorecard's measure),
  for everyone and for each group (sex, age, race, party), unweighted.
The same people answer both times, so a group shift is not sampling chance: it is changes of answer that did
not cancel out, plus any real change in two weeks.

Writes docs/results/self_agreement_twin2k.md, and .json with the figures the scorecard quotes.
"""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd

from digital_citizens.data import twin2k

OUT = Path("docs/results/self_agreement_twin2k.md")
GROUPS = ["sex", "age", "race", "politics"]
MIN_GROUP = 100


def points_off(a: pd.Series, b: pd.Series) -> float:
    opts = sorted(set(a) | set(b))
    pa = a.value_counts(normalize=True).reindex(opts, fill_value=0)
    pb = b.value_counts(normalize=True).reindex(opts, fill_value=0)
    return float((pa - pb).abs().mean() * 100)


def main() -> None:
    w13, w4 = twin2k.load_responses()
    items = twin2k.retest_items(w13, w4)
    demo = twin2k.demographic_table(w13).set_index("pid")
    A, B = w13.set_index("pid"), w4.set_index("pid")
    rows, cells = [], []
    for it in items:
        a, b = A[it].align(B[it], join="inner")
        m = a.notna() & b.notna()
        a, b = a[m].astype(str), b[m].astype(str)
        rows.append({"item": it, "n": len(a), "options": int(b.nunique()), "match": float((a == b).mean()),
                     "shift_everyone": points_off(a, b)})
        for g in GROUPS:
            lab = demo.loc[a.index, g]
            for v, idx in lab.groupby(lab).groups.items():
                if len(idx) >= MIN_GROUP:
                    cells.append({"item": it, "group": f"{g}: {v}", "n": len(idx), "shift": points_off(a[idx], b[idx])})
    df, cg = pd.DataFrame(rows), pd.DataFrame(cells)
    by_opt = df.groupby("options").agg(items=("item", "size"), match=("match", "mean"), shift=("shift_everyone", "median"))
    lines = [
        "# Same people, asked twice: individual answers change, group answers barely move (Twin-2K-500)", "",
        f"{len(df)} questions asked in waves 1-3 and again in wave 4, about two weeks apart; "
        f"{df.n.median():.0f} people answering both times (middle value across questions). Unweighted. "
        "Points off = average gap per answer option, in percentage points, between the two times' answer shares.", "",
        "| | value |", "|---|---|",
        f"| Share of people giving the same answer both times (average over questions) | {df.match.mean():.1%} |",
        f"| Everyone: shift in answer shares (middle value over questions) | {df.shift_everyone.median():.2f} points |",
        f"| Groups of at least {MIN_GROUP}: shift (middle value over {len(cg)} group-question pairs, "
        f"{cg.group.nunique()} groups) | {cg['shift'].median():.2f} points |",
        f"| Groups: 90th percentile of shift | {cg['shift'].quantile(0.9):.2f} points |", "",
        "## By number of answer options", "",
        "| options | questions | same answer both times | shift, everyone (points) |", "|---|---|---|---|",
        *[f"| {k} | {int(r['items'])} | {r['match']:.1%} | {r['shift']:.2f} |" for k, r in by_opt.iterrows()], "",
        "## By group (middle value over questions)", "",
        "| group | people (middle) | shift (points) |", "|---|---|---|",
        *[f"| {g} | {r['n']:.0f} | {r['shift']:.2f} |" for g, r in cg.groupby("group").agg(n=("n", "median"), shift=("shift", "median")).iterrows()], "",
        "Generated by scripts/self_agreement_twin2k.py.",
    ]
    # Individuals: how far answers move on ordered scales, and whether averaging related questions steadies them
    cat = twin2k.load_catalog()
    exact, near, blocks = [], [], {}
    for it in items:
        cols = cat.get(it.split("_")[0], {}).get("Columns") or []
        a, b = A[it].align(B[it], join="inner")
        m = a.notna() & b.notna()
        a, b = a[m].astype(str), b[m].astype(str)
        opts = [o for o in cols if o in set(a) | set(b)]
        if len(opts) >= 5 and set(a) | set(b) <= set(opts):
            rank = {o: i for i, o in enumerate(opts)}
            ia, ib = a.map(rank), b.map(rank)
            exact.append(float((ia == ib).mean())); near.append(float(((ia - ib).abs() <= 1).mean()))
            blocks.setdefault(it.split("_")[0], []).append((ia, ib))
    big = max(blocks.values(), key=len)
    single_r = float(np.mean([x.corr(y) for x, y in big]))
    avg_r = float(pd.concat([x for x, _ in big], axis=1).mean(axis=1).corr(pd.concat([y for _, y in big], axis=1).mean(axis=1)))
    block_id = max(blocks, key=lambda k: len(blocks[k]))
    lines[-1:-1] = [
        "## Individuals: small moves, and averaging related questions", "",
        f"Ordered questions with five or more choices ({len(exact)}): same answer both times {np.mean(exact):.1%}; "
        f"within one step {np.mean(near):.1%}.", "",
        f"The {len(big)} items of {block_id} ({(cat.get(block_id, {}).get('QuestionText') or '').strip()[:60]}): "
        f"first-round vs second-round correlation {single_r:.2f} for a single item on average, {avg_r:.2f} for each person's "
        "average over all of them.", ""]
    OUT.write_text("\n".join(lines) + "\n")
    per_group = cg.groupby("group").agg(n=("n", "median"), shift=("shift", "median"))
    long_scales = df[df.options >= 6]
    OUT.with_suffix(".json").write_text(json.dumps({
        "people": int(len(A.index.intersection(B.index))), "questions": len(df),
        "match": df.match.mean(), "match_yes_no": df[df.options == 2].match.mean(),
        "match_6_7_options": long_scales.match.mean(), "match_6_7_options_max_item": long_scales.match.max(),
        "shift_everyone": df.shift_everyone.median(), "shift_typical_group": cg["shift"].median(),
        "group_size_vs_shift_spearman": per_group.n.corr(per_group["shift"], method="spearman"),
        "ordered_5plus_items": len(exact), "ordered_exact": float(np.mean(exact)), "ordered_within_one_step": float(np.mean(near)),
        "average_block": block_id, "average_block_items": len(big), "single_item_r": single_r, "average_r": avg_r,
        "groups": per_group.reset_index().to_dict("records")}, indent=1))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
